"""Create native EnergyPlus indoor living walls on per-zone internal mass."""

import math

from cosimulator.idf.utils.upsert_named_idf_object import upsert_named_idf_object
from cosimulator.idf.utils.wall_area import calculate_green_wall_area_by_zone
from cosimulator.schemas.simulation_context import PlantSimulation

PREFIX = "CozyBench Hydroponic "
AVAILABILITY_SCHEDULE = PREFIX + "Availability"
LED_INTENSITY_SCHEDULE = PREFIX + "LED Intensity"
BACKING_CONSTRUCTION = "Interior Partition"
LIGHTS_ON_HOUR = 8
LIGHTS_OFF_HOUR = 22


def _remove_generated_objects(idf) -> None:
    """Remove only plant-coupling objects generated by this configurator."""
    for kind in ("OTHEREQUIPMENT", "INTERNALMASS", "INDOORLIVINGWALL"):
        for obj in list(idf.idfobjects[kind]):
            if str(obj.Name).startswith(PREFIX):
                idf.removeidfobject(obj)
    for obj in list(idf.idfobjects["SCHEDULE:CONSTANT"]):
        name = str(obj.Name)
        if name.casefold() == AVAILABILITY_SCHEDULE.casefold() or name.startswith(PREFIX) and name.endswith((" Plant Latent Load", " Plant Sensible Load")):
            idf.removeidfobject(obj)
    for obj in list(idf.idfobjects["SCHEDULE:COMPACT"]):
        if str(obj.Name).casefold() == LED_INTENSITY_SCHEDULE.casefold():
            idf.removeidfobject(obj)


def _validate_profile(profile: dict) -> tuple[float, float]:
    """Return valid reference panel and leaf areas from the plant profile."""
    if int(profile.get("schema_version", 0)) < 5:
        raise ValueError("Plant response grid must be schema version 5 or later")
    leaf_area = float(profile.get("total_leaf_area_m2", 0))
    panel_area = float(profile.get("panel_area_m2", 1.0))
    if not (math.isfinite(leaf_area) and leaf_area > 0 and math.isfinite(panel_area) and panel_area > 0):
        raise ValueError("Plant profile must contain valid leaf and reference-panel areas")
    return leaf_area, panel_area


def _add_led_intensity_schedule(idf) -> None:
    """Use the same daily 08:00–22:00 light period as the CO2 plant profile."""
    schedule = idf.newidfobject(
        "SCHEDULE:COMPACT",
        Name=LED_INTENSITY_SCHEDULE,
        Schedule_Type_Limits_Name="Fraction",
    )
    fields = ("Through: 12/31", "For: AllDays", "Until: 08:00", 0.0, "Until: 22:00", 1.0, "Until: 24:00", 0.0)
    for index, value in enumerate(fields, start=1):
        setattr(schedule, f"Field_{index}", value)


def add_indoor_living_walls(*, idf, zone_names: set[str], settings: PlantSimulation, profile: dict):
    """Add one InternalMass and one native IndoorLivingWall to each covered zone."""
    areas = calculate_green_wall_area_by_zone(
        idf=idf, green_wall_size=settings.green_wall_size,
        idf_zone_names=zone_names, coverage_percentage=settings.coverage_percentage,
    )
    _remove_generated_objects(idf)
    eligible = {zone: area for zone, area in areas.items() if area > 0}
    if not eligible:
        return idf

    if not any(str(obj.Name).strip().casefold() == BACKING_CONSTRUCTION.casefold() for obj in idf.idfobjects["CONSTRUCTION"]):
        raise ValueError(f"Required living-wall backing construction '{BACKING_CONSTRUCTION}' is missing")
    leaf_area_per_panel, reference_panel_area = _validate_profile(profile)
    upsert_named_idf_object(
        idf, "SCHEDULE:CONSTANT", AVAILABILITY_SCHEDULE,
        Schedule_Type_Limits_Name="Fraction", Hourly_Value=1.0,
    )
    _add_led_intensity_schedule(idf)

    for zone_name, wall_area_m2 in sorted(eligible.items()):
        internal_mass_name = f"{PREFIX}{zone_name} Internal Mass"
        living_wall_name = f"{PREFIX}{zone_name} Indoor Living Wall"
        total_leaf_area_m2 = leaf_area_per_panel * wall_area_m2 / reference_panel_area
        # EnergyPlus documents a maximum LAI of 2.0 for IndoorLivingWall.
        total_leaf_area_m2 = min(total_leaf_area_m2, 2.0 * wall_area_m2)
        upsert_named_idf_object(
            idf, "INTERNALMASS", internal_mass_name,
            Construction_Name=BACKING_CONSTRUCTION,
            Zone_or_ZoneList_Name=zone_name,
            Surface_Area=wall_area_m2,
        )
        upsert_named_idf_object(
            idf, "INDOORLIVINGWALL", living_wall_name,
            Surface_Name=internal_mass_name,
            Schedule_Name=AVAILABILITY_SCHEDULE,
            Evapotranspiration_Calculation_Method="Penman-Monteith",
            Lighting_Method="LED",
            LED_Intensity_Schedule_Name=LED_INTENSITY_SCHEDULE,
            Total_Leaf_Area=total_leaf_area_m2,
            LED_Nominal_Intensity=settings.lighting_level.ppfd_umol_m2_s,
            # The user-specified PPFD is known; fixture wattage is not.
            # Zero prevents inventing LED electricity/heat on top of the IDF.
            LED_Nominal_Power=0.0,
            Radiant_Fraction_of_LED_Lights=0.0,
        )
    return idf
